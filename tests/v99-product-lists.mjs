import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
const app=read('app.js'),live=read('live-client.js'),gas=read('gas/Api.gs'),css=read('styles.css');
for(const [name,source] of [['app',app],['live',live],['gas',gas]])new vm.Script(source,{filename:name});
assert.match(app,/function unifiedProductResults\(\)/);
assert.match(app,/在庫管理中の商品/);
assert.match(app,/在庫管理していない商品/);
assert.match(app,/unified-search-sticky/);
assert.match(app,/data-unified-manage/);
assert.match(app,/data-unified-unmanaged-toggle/);
assert.match(app,/productDisplayPins/);
assert.doesNotMatch(app,/productModeUndo\?\s*`/);
assert.match(app,/productCreateMode='stock'/);
assert.match(live,/productListModes:workspace\.base/);
assert.doesNotMatch(live,/if\(op\.fields\.list_mode!=='stock'\)p\.in_stock=false/);
assert.doesNotMatch(gas,/if\(payload\.list_mode!=='stock'\)entity\.in_stock=false/);
assert.doesNotMatch(gas,/if\(!payload\.stock_enabled\)entity\.in_stock=false/);
assert.match(gas,/function kurashiTrialProductListsMigrate\(\)/);
assert.match(gas,/function kurashiTrialProductListsVerify\(\)/);
assert.match(css,/\.unified-search-sticky\s*\{/);
assert.match(css,/\.unified-manage-toggle\s*\{/);
console.log('stock-first catalogue, fixed search and preserved in_stock: OK');
